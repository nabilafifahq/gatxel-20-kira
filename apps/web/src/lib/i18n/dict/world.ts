/** Tanggal ISO menjadi "5 November 2026". Nilai yang bukan tanggal dikembalikan apa adanya. */
function tanggal(iso: string): string {
  const d = new Date(`${iso}T00:00:00Z`)
  if (Number.isNaN(d.getTime())) return `${iso}`
  return new Intl.DateTimeFormat('id', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(d)
}

