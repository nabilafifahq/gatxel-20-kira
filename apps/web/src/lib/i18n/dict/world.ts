export const world = { en, id }

type WorldDict = typeof en

/**
 * Teks menurut id untuk data di @kira/core. Id baru yang belum masuk kamus tetap terbaca lewat teks Inggris sumbernya
 * sampai kuncinya ditambahkan.
 */
function byId(map: object, key: string): string | undefined {
  return (map as Record<string, string | undefined>)[key]
}

export function itemName(w: WorldDict, itemId: string, source: string): string {
  return byId(w.items, itemId) ?? source
}

export function setName(w: WorldDict, setId: string, source: string): string {
  return byId(w.sets, setId) ?? source
}

export function treatName(w: WorldDict, treatId: string, source: string): string {
  return (w.treats as Record<string, { name: string } | undefined>)[treatId]?.name ?? source
}

export function treatLine(w: WorldDict, treatId: string, source: string): string {
  return (w.treats as Record<string, { line: string } | undefined>)[treatId]?.line ?? source
}

export function topicName(w: WorldDict, topicId: string): string {
  return byId(w.album.topics, topicId) ?? topicId
}
